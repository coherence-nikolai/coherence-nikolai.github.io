import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const app=readFileSync(fileURLToPath(new URL('../app.js',import.meta.url)),'utf8');
const css=readFileSync(fileURLToPath(new URL('../styles.css',import.meta.url)),'utf8');
const extract=(name,next)=>app.slice(app.indexOf(`function ${name}(`),app.indexOf(`function ${next}(`));
const calls=[];
const stage={style:{setProperty:(...args)=>calls.push(['style',...args])},classList:{toggle:(...args)=>calls.push(['class',...args])},scrollTo:(...args)=>calls.push(['scroll',...args]),focus:options=>calls.push(['focus',options]),scrollIntoView:options=>calls.push(['intoView',options])};
const context=vm.createContext({state:{view:'comicReader',comicZoom:1},comicSwipeStart:{x:1},document:{querySelector:()=>stage},phrase:english=>english,announce:copy=>calls.push(['announce',copy])});
vm.runInContext(extract('setComicZoom','focusComicPageStart')+extract('focusComicPageStart','turnComicPage'),context);
context.setComicZoom(3);
assert.equal(context.state.comicZoom,3);
assert.equal(context.comicSwipeStart,null);
assert.deepEqual(calls.find(x=>x[0]==='style'),['style','--comic-zoom',3]);
assert.deepEqual(calls.find(x=>x[0]==='scroll'),['scroll',0,0]);
const before=calls.length;
for(const invalid of [0,-1,4,NaN,Infinity,'3'])context.setComicZoom(invalid);
assert.equal(calls.length,before,'Unsupported zoom values must have no effects.');
context.setComicZoom(1);
assert.equal(context.state.comicZoom,1);
context.state.view='landing';context.setComicZoom(2);
assert.equal(context.state.comicZoom,1,'Zoom must not mutate a different screen.');
context.focusComicPageStart();
assert.equal(calls.find(x=>x[0]==='intoView')[1].block,'start');
assert(app.includes('state.comicZoom === 1 && !event.target.matches'));
assert(app.includes('state.view !== "comicReader" || state.comicZoom > 1'));
assert(css.includes('width: calc(100% * var(--comic-zoom, 1))'));
assert(css.includes('overflow: auto; touch-action: pan-x pan-y pinch-zoom'));
console.log('Comic zoom logic passes: valid ranges, reset, screen guard, swipe/keyboard guards and scrollable art dimensions. Browser visual checks remain separate.');
